function detectBrowserLocale(): Locale {
  if (typeof window === "undefined") return defaultLocale;
  const stored = window.localStorage.getItem(localeStorageKey);
  if (isLocale(stored)) return stored;

  const cookieLocale = document.cookie
    .split("; ")
    .find((item) => item.startsWith(`${localeCookieKey}=`))
    ?.slice(localeCookieKey.length + 1);
  if (cookieLocale) {
    const decodedLocale = decodeURIComponent(cookieLocale);
    if (isLocale(decodedLocale)) return decodedLocale;
  }

  const candidates = window.navigator.languages?.length ? window.navigator.languages : [window.navigator.language];
  for (const language of candidates) {
    if (isLocale(language)) return language;
    const normalized = language.toLowerCase();
    if (normalized.startsWith("zh")) return "zh-CN";
    if (normalized.startsWith("pt")) return "pt-BR";
    if (normalized.startsWith("ru")) return "ru";
    if (normalized.startsWith("vi")) return "vi";
    if (normalized.startsWith("de")) return "de";
    if (normalized.startsWith("fr")) return "fr";
  }
  return defaultLocale;
}

export function useStudioI18n(initialLocale: Locale = defaultLocale) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);

  useEffect(() => {
    const detectedLocale = detectBrowserLocale();
    setLocaleState(detectedLocale);
    persistLocalePreference(detectedLocale);
  }, []);

  function setLocale(localeValue: Locale) {
    persistLocalePreference(localeValue);
    setLocaleState(localeValue);
  }

  function t(key: string, values?: Record<string, string | number | null | undefined>) {
    let template =
      studioDreamfaceIoMessages[locale]?.[key] ||
      studioFalErrorMessages[locale]?.[key] ||
      (locale === "de" ? studioGermanMessages[key] : undefined) ||
      (locale === "fr" ? studioFrenchMessages[key] : undefined) ||
      studioAdditionalMessages[locale]?.[key] ||
      messages[locale]?.[key] ||
      workflowMessages[locale]?.[key] ||
      studioHomeMessages[locale]?.[key] ||
      studioFeedbackMessages[locale]?.[key] ||
      studioModelMessages[locale]?.[key] ||
      messages[defaultLocale]?.[key] ||
      workflowMessages[defaultLocale]?.[key] ||
      studioHomeMessages[defaultLocale]?.[key] ||
      studioFeedbackMessages[defaultLocale]?.[key] ||
      studioFalErrorMessages[defaultLocale]?.[key] ||
      studioModelMessages[defaultLocale]?.[key] ||
      key;
    if (values) {
      for (const [name, value] of Object.entries(values)) {
        template = template.replaceAll(`{${name}}`, String(value ?? ""));
      }
    }
    return template;
  }

  return {
    locale,
    localeLabels,
    locales,
    setLocale,
    t
  };
}
