function detectBrowserLocale(): Locale {
  if (typeof window === "undefined") return defaultLocale;
  const stored = window.localStorage.getItem(localeStorageKey);
  if (isLocale(stored)) return stored;

  const cookieLocale = document.cookie
    .split("; ")
    .find((item) => item.startsWith(`${localeCookieKey}=`))
    ?.slice(localeCookieKey.length + 1);
  if (cookieLocale) {
    const decodedLocale = decodeURIComponent(cookieLocale);
    if (isLocale(decodedLocale)) return decodedLocale;
  }

  const candidates = window.navigator.languages?.length ? window.navigator.languages : [window.navigator.language];
  for (const language of candidates) {
    if (isLocale(language)) return language;
    const normalized = language.toLowerCase();
    if (
      normalized === "zh-tw" ||
      normalized === "zh-hk" ||
      normalized === "zh-mo" ||
      normalized.startsWith("zh-hant")
    ) return "zh-TW";
    if (normalized.startsWith("zh")) return "zh-CN";
    if (normalized.startsWith("pt")) return "pt-BR";
    if (normalized.startsWith("ru")) return "ru";
    if (normalized.startsWith("vi")) return "vi";
    if (normalized.startsWith("de")) return "de";
    if (normalized.startsWith("fr")) return "fr";
    if (normalized.startsWith("ja")) return "ja";
    if (normalized.startsWith("th")) return "th";
    if (normalized.startsWith("nl")) return "nl";
    if (normalized.startsWith("he") || normalized.startsWith("iw")) return "he";
    if (normalized.startsWith("ko")) return "ko";
    if (normalized.startsWith("es")) return "es";
    if (normalized.startsWith("it")) return "it";
    if (normalized.startsWith("ar")) return "ar";
  }
  return defaultLocale;
}

