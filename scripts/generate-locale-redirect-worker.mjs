import assert from 'node:assert/strict';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import ts from 'typescript';
import { projectLoader } from './load-project-ts.mjs';

const input = 'src/i18n/locale-preference.ts';
const source = ts.createSourceFile(input, readFileSync(input, 'utf8'), ts.ScriptTarget.Latest, true);
const resolver = source.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === 'createLocalePreferenceResolver');
assert.ok(resolver, 'The shared locale resolver must exist');
const compiled = ts.transpileModule(resolver.getText(source).replace(/^export /, ''), {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext }
}).outputText.trim();
const { locales, defaultLocale, localeCookieKey } = projectLoader()('src/i18n/routing.ts');
const content = `// Generated by npm run generate:locale-redirect. Copy this entire file into a module Worker.
// Edit src/i18n/locale-preference.ts instead of changing the generated language logic.
// No external imports, credentials, bindings or npm dependencies are required.

${compiled}

const resolveLocale = createLocalePreferenceResolver(${JSON.stringify(locales)}, ${JSON.stringify(defaultLocale)}, ${JSON.stringify(localeCookieKey)});

export default {
  async fetch(request, _env, context) {
    const url = new URL(request.url);
    if (url.hostname !== "dreamface.io") return new Response("Not found", { status: 404 });
    if (url.pathname !== "/" || (request.method !== "GET" && request.method !== "HEAD")) {
      // Preserve the original request, response, cookies, body and cache behavior.
      // Never retry origin POST requests if fetch fails.
      return fetch(request);
    }

    // A root GET/HEAD can safely fall back to the matching Next.js middleware.
    context?.passThroughOnException?.();
    url.protocol = "https:";
    url.port = "";
    url.pathname = "/" + resolveLocale(request.headers);
    return new Response(null, {
      status: 307,
      headers: {
        "Location": url.toString(),
        "Cache-Control": "private, no-store",
        "Vary": "Accept-Language, Cookie",
        "X-DreamFace-Locale-Redirect": "edge"
      }
    });
  }
};
`;

const output = 'cloudflare/locale-redirect-worker.mjs';
if (process.argv.includes('--check')) assert.equal(readFileSync(output, 'utf8'), content, 'Run npm run generate:locale-redirect to update the Worker');
else { mkdirSync('cloudflare', { recursive: true }); writeFileSync(output, content); }
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} the standalone Cloudflare locale Worker from the shared resolver and all ${locales.length} supported locales.`);
